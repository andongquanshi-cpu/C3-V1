/** 用一个 6-8 元组把坐标序列化成 prompt 可读文本 */
export interface AngleCoordinate {
  [axisKey: string]: string;
}

/** 把坐标格式化为「轴=值」的多行字符串，塞进 prompt */
export function formatCoordinateForPrompt(
  coord: AngleCoordinate,
  axes: AngleAxis[] = ANGLE_AXES,
): string {
  return axes
    .map((axis) => {
      const value = coord[axis.key];
      if (!value) return null;
      return `  - ${axis.label}：${value}`;
    })
    .filter(Boolean)
    .join("\n");
}

/** 把坐标压成短字符串，用于历史去重（跨批次记忆） */
export function coordinateFingerprint(coord: AngleCoordinate): string {
  return ANGLE_AXES.map((axis) => `${axis.key}:${coord[axis.key] || ""}`).join("|");
}
