/**
 * 创意角度维度轴库
 * -------------------------------------------------------
 * 目标：把"创意的开放性"从模型自由发挥，前移到"结构化维度采样"。
 * 每次生成 N 个角度时，先在这 8 个正交轴上为每个角度骰出一个坐标
 * （见 angle-sampler.ts），然后把坐标写进 prompt，作为**每条角度**
 * 必须遵守的差异化约束。
 *
 * 设计原则：
 * 1. 变数最大化：8 个轴 × 每轴 8-12 个取值 → 单批次组合空间 ≥ 2^28
 * 2. 正交性：轴之间要尽量独立，避免"人称=第一视角"暗含"情绪=亲历"
 * 3. 可执行：取值必须是模型能立刻理解并落地为具体写法的短语
 * 4. 中性：不预设"哪个更好"，采样器应无偏抽取
 *
 * 合规红线暂未纳入（用户明确要求后置处理），未来可加 `disabledIn`
 * 字段并在 axis-activator 里过滤。
 */

export interface AngleAxis {
  /** 轴 ID，用于坐标序列化 */
  key: string;
  /** 展示给模型看的轴名称（中文） */
  label: string;
  /** 一句话说明这个轴决定什么 */
  hint: string;
  /** 取值池 */
  values: string[];
}

